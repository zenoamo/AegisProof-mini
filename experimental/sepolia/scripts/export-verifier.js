import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ejs from "ejs";
import * as snarkjs from "snarkjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const vkPath = path.join(root, "keys", "verification_key.json");
const zkeyPath = path.join(root, "circuit", "mini.zkey");
const templatePath = path.join(
  root,
  "node_modules",
  "snarkjs",
  "templates",
  "verifier_groth16.sol.ejs",
);
const outPath = path.join(
  root,
  "experimental",
  "sepolia",
  "contracts",
  "Groth16Verifier.sol",
);

function usedFields(vk) {
  return JSON.stringify({
    protocol: vk.protocol,
    curve: vk.curve,
    nPublic: vk.nPublic,
    vk_alpha_1: vk.vk_alpha_1,
    vk_beta_2: vk.vk_beta_2,
    vk_gamma_2: vk.vk_gamma_2,
    vk_delta_2: vk.vk_delta_2,
    IC: vk.IC,
  });
}

const stored = JSON.parse(fs.readFileSync(vkPath, "utf8"));
if (stored.protocol !== "groth16" || stored.curve !== "bn128" || stored.nPublic !== 1) {
  throw new Error("verification_key.json は groth16 / bn128 / nPublic=1 ではありません");
}
if (!Array.isArray(stored.IC) || stored.IC.length !== 2) {
  throw new Error("verification_key.json の IC 長が public input 1 個と一致しません");
}

const exported = await snarkjs.zKey.exportVerificationKey(zkeyPath);
if (usedFields(exported) !== usedFields(stored)) {
  throw new Error("mini.zkey から書き出した検証鍵が verification_key.json と一致しません");
}

const template = fs.readFileSync(templatePath, "utf8");
const source = ejs.render(template, stored);
if (!source.includes("uint[1] calldata _pubSignals")) {
  throw new Error("生成した verifier の publicSignals が uint[1] ではありません");
}
if (!source.includes("contract Groth16Verifier")) {
  throw new Error("生成した verifier のコントラクト名が不正です");
}

const header =
  "// Generated by experimental/sepolia/scripts/export-verifier.js\n// Source: keys/verification_key.json (checked against circuit/mini.zkey). Do not edit by hand.\n";
fs.writeFileSync(outPath, header + source);
console.log("wrote", path.relative(root, outPath));
process.exit(0);
